#!/bin/bash
# priprav.sh — prepares a Mac for the company-context repositories. Run once; safe to run again.
#
#   bash -c "$(curl -fsSL https://raw.githubusercontent.com/TAKTIK-GROUP/kontext-start/main/priprav.sh)"
#
# (bash -c "$(…)" and not curl | bash: the prompts of sudo, gh and read need the terminal on stdin.)
# Installs what is missing (Git via Apple's Command Line Tools, Node.js LTS, GitHub CLI, VS Code),
# logs in to GitHub, clones every repository of the organization the person can write to into
# ~/Kontext, installs the Claude Code and Codex extensions and opens VS Code. Ends with a "PRIPRAVA:" line the
# person sends to the administrator when something fails. Bash 3.2 (the macOS default).
# Generated by scripts/new-start.mjs from start/ in the kit — edit there.
# KONTEXT_ORG and KONTEXT_PRIECINOK override the organization and the target folder (tests).
set -u

ORG='TAKTIK-GROUP'
[ -n "${KONTEXT_ORG:-}" ] && ORG="$KONTEXT_ORG"
DIR="${KONTEXT_PRIECINOK:-$HOME/Kontext}"
NODE_LINE=24        # Node.js LTS line installed when Node is missing (the tools need ≥ 18)
EXTENSIONS='anthropic.claude-code:Claude_Code openai.chatgpt:Codex'   # <id>:<name, _ = space>; the person uses either
SKIP_REPOS='kontext-start kontext-sprava'   # repositories of the organization nobody writes context into
PATH="$PATH:/usr/local/bin:/opt/homebrew/bin"
unset FORCE_COLOR CLICOLOR_FORCE GH_FORCE_TTY   # tool output is parsed: no colour codes
export NO_COLOR=1
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

say()  { printf '\n\033[1m%s\033[0m\n' "$*"; }
ok()   { printf '  ✓ %s\n' "$*"; }
info() { printf '  %s\n' "$*"; }
fail() { # fail <CODE> <message for the person>
  printf '\n\033[31m✗ %s\033[0m\n' "$2"
  printf '\nNiečo sa nepodarilo. Pošli správcovi tento riadok (a pokojne aj fotku obrazovky):\n\n'
  printf '  PRIPRAVA: CHYBA %s (Mac %s)\n\n' "$1" "$(sw_vers -productVersion 2>/dev/null)"
  exit 1
}

need_sudo() {
  [ -n "${SUDO_OK:-}" ] && return
  info 'Na inštaláciu treba heslo, ktorým sa prihlasuješ do notebooku.'
  info 'Pri písaní sa nič nezobrazuje — to je v poriadku. Napíš ho a stlač Enter.'
  sudo -v || fail ADMIN 'Inštalácia potrebuje heslo správcu notebooku. Ak ho nemáš, ozvi sa správcovi.'
  SUDO_OK=1
}

install_pkg() { # install_pkg <file> <CODE>
  need_sudo
  sudo installer -pkg "$1" -target / >/dev/null || fail "$2" 'Inštalácia sa nepodarila.'
  hash -r
}

node_major() { # plain digits: node -p would colour them under FORCE_COLOR
  v=$(node -e 'process.stdout.write(String(parseInt(process.versions.node)))' 2>/dev/null)
  case "$v" in ''|*[!0-9]*) echo 0 ;; *) echo "$v" ;; esac
}

[ "$(uname)" = Darwin ] || fail SYSTEM 'Tento príkaz je pre Mac. Na Windows použi príkaz pre PowerShell z návodu.'
case "$ORG" in *'{{'*|'') fail ORGANIZACIA 'V skripte chýba názov organizácie na GitHube.' ;; esac

say 'Príprava notebooku na firemný kontext'
info "Organizácia: $ORG · priečinok: $DIR"
info 'Trvá to 10–20 minút, väčšinu času sa len sťahuje. Okno nezatváraj.'

# 1. Git (Apple Command Line Tools)
say '1/6 Git'
if xcode-select -p >/dev/null 2>&1 && git --version >/dev/null 2>&1; then
  ok "$(git --version)"
else
  info 'Otvorí sa okno od Apple: klikni „Inštalovať“ a potom „Súhlasím“. Počkaj, kým sa dokončí.'
  xcode-select --install >/dev/null 2>&1
  waited=0
  until xcode-select -p >/dev/null 2>&1 && git --version >/dev/null 2>&1; do
    [ "$waited" -ge 2700 ] && fail GIT 'Inštalácia nástrojov Apple sa nedokončila. Spusti príkaz znova.'
    sleep 10; waited=$((waited + 10))
  done
  ok "$(git --version)"
fi

# 2. Node.js (runs the repository's tools)
say '2/6 Node.js'
if command -v node >/dev/null 2>&1 && [ "$(node_major)" -ge 18 ]; then
  ok "Node.js $(node --version)"
else
  info 'Sťahujem Node.js…'
  base="https://nodejs.org/dist/latest-v${NODE_LINE}.x"
  line=$(curl -fsSL "$base/SHASUMS256.txt" | grep '\.pkg$' | head -1)
  sum=${line%% *}; file=${line##* }
  [ -n "$file" ] && curl -fsSL -o "$TMP/$file" "$base/$file" || fail NODE 'Node.js sa nepodarilo stiahnuť. Skontroluj internet a spusti príkaz znova.'
  [ "$(shasum -a 256 "$TMP/$file" | cut -d' ' -f1)" = "$sum" ] || fail NODE 'Stiahnutý Node.js je poškodený. Spusti príkaz znova.'
  install_pkg "$TMP/$file" NODE
  command -v node >/dev/null 2>&1 && [ "$(node_major)" -ge 18 ] || fail NODE 'Node.js sa nenainštaloval.'
  ok "Node.js $(node --version)"
fi

# 3. GitHub CLI (logs in, submissions open pull requests)
say '3/6 GitHub CLI'
if command -v gh >/dev/null 2>&1; then
  ok "$(gh --version | head -1)"
else
  info 'Sťahujem GitHub CLI…'
  url=$(curl -fsSL https://api.github.com/repos/cli/cli/releases/latest | grep -o 'https://[^"]*_macOS_universal\.pkg' | head -1)
  [ -n "$url" ] && curl -fsSL -o "$TMP/gh.pkg" "$url" || fail GH_INSTALACIA 'GitHub CLI sa nepodarilo stiahnuť. Skontroluj internet a spusti príkaz znova.'
  install_pkg "$TMP/gh.pkg" GH_INSTALACIA
  command -v gh >/dev/null 2>&1 || fail GH_INSTALACIA 'GitHub CLI sa nenainštaloval.'
  ok "$(gh --version | head -1)"
fi

# 4. VS Code
say '4/6 VS Code'
CODE=$(command -v code 2>/dev/null)
for app in '/Applications/Visual Studio Code.app' "$HOME/Applications/Visual Studio Code.app"; do
  [ -z "$CODE" ] && [ -x "$app/Contents/Resources/app/bin/code" ] && CODE="$app/Contents/Resources/app/bin/code"
done
if [ -n "$CODE" ]; then
  ok 'VS Code je nainštalovaný'
else
  info 'Sťahujem VS Code…'
  curl -fsSL -o "$TMP/vscode.zip" 'https://update.code.visualstudio.com/latest/darwin-universal/stable' \
    && ditto -xk "$TMP/vscode.zip" "$TMP/vscode" \
    || fail VSCODE 'VS Code sa nepodarilo stiahnuť. Skontroluj internet a spusti príkaz znova.'
  app='/Applications/Visual Studio Code.app'
  if ! ditto "$TMP/vscode/Visual Studio Code.app" "$app" 2>/dev/null; then
    need_sudo
    sudo ditto "$TMP/vscode/Visual Studio Code.app" "$app" && sudo chown -R "$(id -un)" "$app" \
      || fail VSCODE 'VS Code sa nepodarilo nainštalovať do Aplikácií.'
  fi
  CODE="$app/Contents/Resources/app/bin/code"
  ok 'VS Code je nainštalovaný'
fi

for ext in $EXTENSIONS; do
  name=$(printf %s "${ext#*:}" | tr _ ' ')
  "$CODE" --install-extension "${ext%%:*}" >/dev/null 2>&1 && ok "rozšírenie $name" \
    || info "Rozšírenie $name nainštaluješ vo VS Code (ponúkne ho samo)."
done

# 5. GitHub login, organization, Git identity
say '5/6 Prihlásenie do GitHubu'
gh_login() {
  info 'Teraz sa prihlásiš do GitHubu:'
  info '  1. Na otázku „Authenticate Git with your GitHub credentials?“ stlač Enter.'
  info '  2. Pri „Press Enter to open github.com/login/device“ stlač Enter. Kód je už skopírovaný.'
  info '  3. V prehliadači vlož kód (Cmd + V), klikni „Continue“ a „Authorize“. Potom sa vráť sem.'
  info 'Ak je prehliadač prihlásený iným účtom GitHub, otvor github.com/login/device'
  info 'v anonymnom okne (Cmd + Shift + N) a kód vlož tam.'
  printf '\n\n'   # gh redraws its prompt over the last lines — keep the instructions above it
  gh auth login --hostname github.com --git-protocol https --web \
    || fail PRIHLASENIE 'Prihlásenie do GitHubu sa nedokončilo. Spusti príkaz znova.'
}
gh auth status --hostname github.com >/dev/null 2>&1 || gh_login
login=$(gh api user --jq .login 2>/dev/null)
ok "prihlásený(á) ako $login — musí to byť tvoj pracovný účet"
gh auth setup-git --hostname github.com >/dev/null 2>&1 || fail PRIHLASENIE 'Git sa nepodarilo prepojiť s prihlásením do GitHubu.'

relogged=''
for attempt in 1 2 3 4; do
  state=$(gh api "user/memberships/orgs/$ORG" --jq .state 2>/dev/null)
  [ "$state" = active ] && break
  if [ "$state" != pending ] && [ -z "$relogged" ]; then
    info "Účet $login nie je v organizácii $ORG. Možno si v prehliadači prihlásený(á) iným účtom."
    printf '  Prihlásiť sa iným účtom? Napíš A a stlač Enter (len Enter = koniec): '
    answer=''; read -r answer
    case "$answer" in
      [AaYy]*)
        relogged=1
        gh auth logout --hostname github.com --user "$login" >/dev/null 2>&1
        gh_login
        login=$(gh api user --jq .login 2>/dev/null)
        ok "prihlásený(á) ako $login"
        gh auth setup-git --hostname github.com >/dev/null 2>&1 || fail PRIHLASENIE 'Git sa nepodarilo prepojiť s prihlásením do GitHubu.'
        continue ;;
    esac
  fi
  [ "$state" = pending ] || fail POZVANKA "Účet $login nie je členom organizácie $ORG. Pozvánka mohla prísť na iný e-mail alebo vypršala — ozvi sa správcovi."
  [ "$attempt" = 4 ] && fail POZVANKA 'Pozvánka do organizácie stále nie je prijatá.'
  info 'Ešte si neprijal(a) pozvánku do firemnej organizácie. Otváram ju v prehliadači —'
  info 'klikni „Join“ (ak GitHub žiada dvojstupňové overenie, najprv ho nastav).'
  open "https://github.com/orgs/$ORG/invitation" 2>/dev/null
  printf '  Keď pozvánku prijmeš, stlač tu Enter. '
  read -r _
done
ok "člen(ka) organizácie $ORG"

if [ -z "$(git config --global user.name)" ]; then
  name=$(gh api user --jq '.name // ""' 2>/dev/null)
  while [ -z "$name" ]; do printf '  Napíš svoje meno a priezvisko a stlač Enter: '; read -r name; done
  git config --global user.name "$name"
fi
if [ -z "$(git config --global user.email)" ]; then
  git config --global user.email "$(gh api user --jq '"\(.id)+\(.login)@users.noreply.github.com"')"
fi
ok "podpis v Gite: $(git config --global user.name)"

# 6. Repositories
say '6/6 Tvoje repozitáre'
repos=''
for full in $(gh api --paginate 'user/repos?per_page=100' --jq '.[] | select(.permissions.push) | .full_name' 2>/dev/null); do
  owner=${full%%/*}; name=${full#*/}
  [ "$(printf %s "$owner" | tr '[:upper:]' '[:lower:]')" = "$(printf %s "$ORG" | tr '[:upper:]' '[:lower:]')" ] || continue
  case " $SKIP_REPOS " in *" $name "*) continue ;; esac
  repos="$repos $name"
done
set -- $(printf '%s\n' $repos | sort)
[ $# -gt 0 ] || fail ZIADNY_REPOZITAR "V organizácii $ORG ešte nemáš prístup k žiadnej oblasti. Ozvi sa správcovi."
if [ $# -gt 1 ]; then
  info 'Môžeš zapisovať do viacerých repozitárov:'
  i=0; for r in "$@"; do i=$((i + 1)); printf '    %d) %s\n' "$i" "$r"; done
  printf '  Napíš čísla tých, ktoré chceš stiahnuť (napr. 1 3), alebo len Enter pre všetky: '
  read -r pick
  if [ -n "$pick" ]; then
    chosen=''
    for n in $pick; do
      case "$n" in *[!0-9]*|'') continue ;; esac
      [ "$n" -ge 1 ] && [ "$n" -le $# ] && eval "chosen=\"\$chosen \${$n}\""
    done
    [ -n "$chosen" ] && set -- $chosen
  fi
fi

mkdir -p "$DIR" || fail KLON "Priečinok $DIR sa nedá vytvoriť."
for r in "$@"; do
  if [ -d "$DIR/$r/.git" ]; then
    ok "$r je už stiahnutý ($DIR/$r)"
  elif [ -e "$DIR/$r" ]; then
    fail KLON "Priečinok $DIR/$r už existuje, ale nie je to repozitár. Nič v ňom nemaž — ozvi sa správcovi."
  else
    git clone -q "https://github.com/$ORG/$r.git" "$DIR/$r" || fail KLON "Repozitár $r sa nepodarilo stiahnuť."
    ok "$r → $DIR/$r"
  fi
done

for r in "$@"; do "$CODE" "$DIR/$r" >/dev/null 2>&1; done

say 'Hotovo. Vo VS Code sa otvorila tvoja oblasť. Posledné kroky:'
info '1. Ak sa VS Code pýta, či dôveruješ autorom priečinka, klikni „Yes, I trust the authors“.'
info '2. Otvor panel Claude alebo Codex (ikona vpravo hore alebo na ľavom boku) a prihlás sa.'
info '   Záložka „Chat“ v pravom paneli je GitHub Copilot — tú nepoužívaj.'
info '3. Keď sa asistent pýta, či dôveruješ tomuto priečinku, potvrď „Yes“.'
info '4. Napíš „ahoj“. Keď ti asistent odpovie, pošli správcovi tento riadok:'
printf '\n  PRIPRAVA: OK %s (Mac %s, %s, Node %s, %s)\n\n' "$(gh api user --jq .login 2>/dev/null)" \
  "$(sw_vers -productVersion 2>/dev/null)" "$(git --version | cut -d' ' -f3)" "$(node --version)" "$*"
